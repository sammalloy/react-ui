// Builds the token outputs from src/tokens.json (W3C design-tokens format):
//   dist/tokens.css   plain CSS variables (primitives, light theme on :root, dark on .dark)
//                     usable from any app, Angular included, with no Tailwind
//   dist/theme.css    Tailwind v4 theme that maps the variables onto utilities
//                     (bg-primary, rounded-lg, ...); imports tokens.css
//   dist/index.js     the resolved tokens as a JS object, plus index.d.ts
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const src = JSON.parse(fs.readFileSync(path.join(pkg, "src/tokens.json"), "utf8"))
const dist = path.join(pkg, "dist")
fs.mkdirSync(dist, { recursive: true })

// Flatten primitives to { "color.neutral.50": value }.
const primitives = {}
;(function walk(node, trail) {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith("$")) continue
    if (val && typeof val === "object" && "$value" in val) primitives[[...trail, key].join(".")] = val.$value
    else if (val && typeof val === "object") walk(val, [...trail, key])
  }
})(src.primitive, [])

const primitiveVar = (ref) => `--bo-${ref.replace(/\./g, "-")}`
const refOf = (value) => value.match(/^\{(.+)\}$/)?.[1]

function resolve(value, seen = []) {
  const ref = refOf(value)
  if (!ref) return value
  if (!(ref in primitives)) throw new Error(`unknown token reference {${ref}}`)
  if (seen.includes(ref)) throw new Error(`circular reference ${[...seen, ref].join(" -> ")}`)
  return resolve(primitives[ref], [...seen, ref])
}
// In CSS, semantic tokens point at the primitive variable so the chain stays visible in devtools.
const cssValue = (value) => (refOf(value) ? `var(${primitiveVar(refOf(value))})` : value)

const themes = Object.keys(src.semantic).filter((k) => !k.startsWith("$") && k !== "shared")
const block = (selector, entries) =>
  `${selector} {\n${entries.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`
const semanticEntries = (group) =>
  Object.entries(src.semantic[group] ?? {})
    .filter(([k]) => !k.startsWith("$"))
    .map(([k, v]) => [`--${k}`, cssValue(v.$value)])

let tokensCss = `/* Generated from src/tokens.json by scripts/build.mjs. Do not edit. */\n`
tokensCss += block(":root", Object.entries(primitives).map(([k, v]) => [primitiveVar(k), v]))
tokensCss += block(":root", [...semanticEntries("shared"), ...semanticEntries("light")])
for (const theme of themes.filter((t) => t !== "light")) {
  tokensCss += block(`.${theme}, [data-theme="${theme}"]`, semanticEntries(theme))
}
fs.writeFileSync(path.join(dist, "tokens.css"), tokensCss)

const colorNames = Object.keys(src.semantic.light).filter((k) => !k.startsWith("$"))
const themeCss = `/* Generated from src/tokens.json by scripts/build.mjs. Do not edit.
   Import after "tailwindcss": maps the token variables onto Tailwind utilities. */
@import "./tokens.css";

@custom-variant dark (&:is(.dark *, [data-theme="dark"] *));

@theme inline {
  --font-sans: var(--font-family-sans);
  --font-mono: var(--font-family-mono);
  --radius-sm: calc(var(--radius) - 4px);
  --radius-md: calc(var(--radius) - 2px);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
${colorNames.map((n) => `  --color-${n}: var(--${n});`).join("\n")}
}

@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  body {
    @apply bg-background text-foreground font-sans;
  }
}
`
fs.writeFileSync(path.join(dist, "theme.css"), themeCss)

const resolved = { primitive: {}, semantic: {} }
for (const [k, v] of Object.entries(primitives)) resolved.primitive[k] = resolve(v)
for (const group of ["shared", ...themes]) {
  resolved.semantic[group] = Object.fromEntries(
    Object.entries(src.semantic[group] ?? {})
      .filter(([k]) => !k.startsWith("$"))
      .map(([k, v]) => [k, resolve(v.$value)])
  )
}
fs.writeFileSync(path.join(dist, "tokens.json"), JSON.stringify(resolved, null, 2) + "\n")
fs.writeFileSync(
  path.join(dist, "index.js"),
  `// Generated by scripts/build.mjs.\nexport const tokens = ${JSON.stringify(resolved, null, 2)}\nexport const themes = ${JSON.stringify(themes)}\n`
)
const semanticType = (group) =>
  `{ ${Object.keys(resolved.semantic[group]).map((k) => JSON.stringify(k) + ": string").join("; ")} }`
fs.writeFileSync(
  path.join(dist, "index.d.ts"),
  `// Generated by scripts/build.mjs.
export declare const tokens: {
  primitive: Record<${Object.keys(primitives).map((k) => JSON.stringify(k)).join(" | ")}, string>
  semantic: {
${["shared", ...themes].map((g) => `    ${g}: ${semanticType(g)}`).join("\n")}
  }
}
export declare const themes: ${JSON.stringify(themes)}
`
)
console.log(`tokens: ${Object.keys(primitives).length} primitives, themes ${themes.join(", ")}`)
